def _declared_terms(expr: dict) -> list[str]:
    names: set[str] = set()
    for rendered in (render_expr(expr),):
        for token in _IDENT_RE.findall(rendered):
            if "_s" in token and re.fullmatch(r"[a-z][a-z0-9_]*_s\d+", token):
                names.add(token)
    return sorted(names)


def export_ea(genome: dict, name: str = "Strategy", bot_id: str = "bot1", magic: int = 900001,
              api_base: str = "https://api.example.com", bot_token: str = "token") -> str:
    """Render a genome into a deterministic MQL5 EA skeleton (SPEC §6.1)."""
    G.validate(genome)
    long_expr, short_expr = render_expr(genome["long"]), render_expr(genome["short"])
    names = sorted(set(_declared_terms(genome["long"])) | set(_declared_terms(genome["short"])))
    decls = "\n".join(f"   double {n} = V(\"{n}\");" for n in names)
    if not decls:
        decls = "   // no series terms in this genome (constant rules)"
    stops = genome["stops"]
    values = {
        "name": name.replace('"', "'"), "bot_id": bot_id.replace('"', "'"), "magic": int(magic),
        "risk_pct": _num(genome["risk"]["risk_pct"]), "api_base": api_base.rstrip("/"),
        "bot_token": bot_token.replace('"', "'"),
        "rsi_period": int(next((t["n"] for t in G.iter_terms(genome["long"]) if t.get("f") == "rsi"), 14)),
        "atr_period": int(stops["atr_period"]),
        "ma_period": int(next((t["n"] for t in G.iter_terms(genome["long"]) if t.get("f") in ("ema", "sma")), 20)),
        "bands_period": int(next((t["n"] for t in G.iter_terms(genome["long"]) if t.get("f") == "bb_pos"), 20)),
        "adx_period": int(next((t["n"] for t in G.iter_terms(genome["long"]) if t.get("f") == "adx"), 14)),
        "sl_mult": _num(stops["sl_atr_mult"]),
        "tp_mult": _num(stops.get("tp_atr_mult") or stops["sl_atr_mult"] * 2.0),
        "series_decls": decls, "long_expr": long_expr, "short_expr": short_expr,
        "atr_period": int(stops["atr_period"]),
    }
    return _EA_TEMPLATE.format(**values)


