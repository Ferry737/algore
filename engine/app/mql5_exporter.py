"""MQL5 exporter — deterministic AST → MQL5 expression renderer + EA templates (SPEC §6).

CLEAN-ROOM DESIGN. ``render_expr`` is the single source of truth for term naming;
the parity tests re-evaluate its output through an independent Python mirror to
prove the Python evaluator and the rendered MQL5 expressions agree.

Term names follow ``<f><n>[k<k>]_s<shift>`` (bb_pos is rendered as ``bbpos``).
Every rendered expression is fully parenthesised so C and Python precedence agree.
"""
from __future__ import annotations

import re

from . import genome as G

_PRICE_F = frozenset(G.PRICE_FEATURES)
_TIME_F = frozenset(G.TIME_FEATURES)
_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def _num(value: float) -> str:
    """Fixed-decimal numeric literal (no exponent — exponent 'e' would look like an identifier)."""
    v = float(value)
    text = format(v, ".10f").rstrip("0").rstrip(".")
    if not text or text == "-":
        return "0"
    if text.startswith("."):
        text = "0" + text
    if text.startswith("-."):
        text = "-0" + text[1:]
    return text


def term_name(term: dict, extra_shift: int = 0) -> str:
    """Render one §7 term as the named series variable used by the Python mirror."""
    if "c" in term:
        return _num(term["c"])
    f = str(term["f"])
    shift = int(term.get("shift", 1)) + int(extra_shift)
    if f in _PRICE_F or f in _TIME_F:
        return f"{f}_s{shift}"
    if f == "bb_pos":
        k = int(round(float(term.get("k", 2.0))))
        return f"bbpos{int(term['n'])}k{k}_s{shift}"
    return f"{f}{int(term['n'])}_s{shift}"


def render_term(term: dict, extra_shift: int = 0) -> str:
    return term_name(term, extra_shift)


def render_expr(expr: dict) -> str:
    """Render a boolean AST node into a fully-parenthesised C-like boolean expression."""
    op = expr["op"]
    # Bitwise & / | / ~ are element-wise for numpy (the parity mirror evals this expression
    # in Python) and are valid integer/bool operators in MQL5. C-style && / || would make
    # Python's truth-value coercion ambiguous on arrays.
    if op == "and":
        return "(" + " & ".join(render_expr(a) for a in expr["args"]) + ")"
    if op == "or":
        return "(" + " | ".join(render_expr(a) for a in expr["args"]) + ")"
    if op == "not":
        return "(~(" + render_expr(expr["arg"]) + "))"
    if op in G.CMP_OPS:
        return f"({render_term(expr['left'])} {op} {render_term(expr['right'])})"
    if op in G.CROSS_OPS:
        a, b = render_term(expr["left"]), render_term(expr["right"])
        pa, pb = render_term(expr["left"], 1), render_term(expr["right"], 1)
        if op == "cross_up":
            return f"((({a} > {b}) & ({pa} <= {pb})))"
        return f"((({a} < {b}) & ({pa} >= {pb})))"
    if op in G.SLOPE_OPS:
        cmp_op = ">" if op == "rising" else "<"
        lookback = max(1, int(expr.get("lookback", 2)))
        parts = []
        for i in range(lookback):
            parts.append(f"({render_term(expr['arg'], i)} {cmp_op} {render_term(expr['arg'], i + 1)})")
        return "(" + " & ".join(parts) + ")"
    raise ValueError(f"unknown op {op!r}")


