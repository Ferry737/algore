<#
.SYNOPSIS
One-time Windows 11 setup: Python venv, npm dependencies, private .env with random keys.
.EXAMPLE
powershell -ExecutionPolicy Bypass -File .\setup.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$engine = Join-Path $root 'engine'
$dashboard = Join-Path $root 'dashboard'
$envPath = Join-Path $root '.env'

function Get-PythonCommand {
    $py = Get-Command py -ErrorAction SilentlyContinue
    if ($py) {
        & py -3.11 -c "import sys; assert sys.version_info >= (3,11)" 2>$null
        if ($LASTEXITCODE -eq 0) { return @('py', '-3.11') }
    }
    foreach ($candidate in @('python', 'python3')) {
        $cmd = Get-Command $candidate -ErrorAction SilentlyContinue
        if ($cmd) {
            & $cmd -c "import sys; assert sys.version_info >= (3,11)" 2>$null
            if ($LASTEXITCODE -eq 0) { return @($candidate) }
        }
    }
    throw 'Python 3.11+ is required. Install it from python.org with "Add Python to PATH".'
}

function New-RandomHex {
    param([int]$Bytes = 32)
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

Write-Host '== AlgoRE Windows setup ==' -ForegroundColor Cyan

$python = Get-PythonCommand
Write-Host "Python: $($python -join ' ')"

$npm = Get-Command npm -ErrorAction SilentlyContinue
if (-not $npm) { throw 'Node.js 20+ with npm is required. Install it from nodejs.org.' }
Write-Host "Node: $(node --version) / npm: $(npm --version)"

if (-not (Test-Path $envPath)) {
    $lines = @(
        '# Generated by windows/setup.ps1. Keep this file private.',
        '# Never commit it. Rotating these keys invalidates old tokens.',
        "ALGORE_JWT_SECRET=$(New-RandomHex)",
        "ALGORE_DASHBOARD_API_KEY=$(New-RandomHex)",
        "ALGORE_PILOT_API_KEY=$(New-RandomHex)",
        'ALGORE_CORS_ORIGINS=http://localhost:3000',
        'ALLOWED_ORIGINS=http://localhost:3000',
        "ALGORE_DB_PATH=$(Join-Path $root 'data\algore.db')",
        'ALGORE_HOST=127.0.0.1',
        'ALGORE_PORT=8000'
    )
    [System.IO.File]::WriteAllLines($envPath, $lines)
    try {
        $acl = Get-Acl -LiteralPath $envPath
        $acl.SetAccessRuleProtection($true, $false)
        $rule = New-Object System.Security.AccessControl.FileSystemAccessRule(
            [System.Security.Principal.WindowsIdentity]::GetCurrent().Name,
            'FullControl', 'Allow')
        $acl.SetAccessRule($rule)
        Set-Acl -LiteralPath $envPath -AclObject $acl
    } catch {
        Write-Warning "Could not restrict .env ACL automatically: $($_.Exception.Message)"
    }
    Write-Host 'Created .env with random keys (values hidden).' -ForegroundColor Green
} else {
    Write-Host '.env already exists; leaving your keys untouched.' -ForegroundColor Green
}

$venvPython = Join-Path $engine '.venv\Scripts\python.exe'
if (-not (Test-Path $venvPython)) {
    Write-Host 'Creating Python virtual environment...'
    $venvPath = Join-Path $engine '.venv'
    if ($python.Count -gt 1) {
        & $python[0] $python[1] -m venv $venvPath
    } else {
        & $python[0] -m venv $venvPath
    }
    if ($LASTEXITCODE -ne 0) { throw 'Failed to create the virtual environment.' }
}

Write-Host 'Installing Python dependencies...'
& $venvPython -m pip install --upgrade pip
& $venvPython -m pip install -r (Join-Path $engine 'requirements.txt')
if ($LASTEXITCODE -ne 0) { throw 'Python dependency install failed.' }

Write-Host 'Installing npm dependencies...'
Push-Location $dashboard
try {
    npm ci
    if ($LASTEXITCODE -ne 0) { throw 'npm dependency install failed.' }
} finally { Pop-Location }

New-Item -ItemType Directory -Force -Path (Join-Path $PSScriptRoot 'run') | Out-Null
Write-Host 'Setup complete. Run start.bat, or start-api.ps1 and start-dashboard.ps1.' -ForegroundColor Green
